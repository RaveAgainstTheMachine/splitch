def _cmd_engine(args: argparse.Namespace) -> int:
    if args.engine_cmd == "status":
        st = get_engine_status(
            check_remote=bool(args.check_remote),
            backend_override=args.backend,
        )
        if args.json:
            print(json.dumps(st.model_dump(mode="json"), indent=2))
            return 0
        cuda_note = f" (CUDA {st.cuda_version})" if st.cuda_version else ""
        print(
            f"Splitch Engine Status ({st.platform}/{st.arch}) — "
            f"recommended backend: {st.recommended_backend}{cuda_note}"
        )
        if st.detected_gpus:
            for g in st.detected_gpus:
                vram_s = f" · {g.vram_total_mb / 1024:.1f} GB" if g.vram_total_mb > 0 else ""
                print(f"  [gpu] GPU {g.index} [{g.vendor}] {g.name}{vram_s}")
        if st.installed:
            for e in st.installed:
                kind = "managed" if e.managed else "system"
                print(
                    f"  [ok] {e.engine:10s} ({kind}) {e.build_tag or e.version or 'present'} — {e.path}"
                )
        else:
            print("  [!]  No local engine binaries installed (run `splitch engine install llama.cpp`)")
        if st.latest_llama_tag:
            flag = "UPDATE AVAILABLE" if st.update_available else "up to date"
            print(
                f"  [i]  Upstream llama.cpp: {st.latest_llama_tag} ({flag})"
                + (f" — asset: {st.matched_asset}" if st.matched_asset else "")
            )
            if st.matched_cudart_asset:
                print(f"       CUDA runtime asset: {st.matched_cudart_asset}")
        if st.error:
            print(f"  [!]  {st.error}", file=sys.stderr)
        return 0

    progress = TerminalProgress()
    res = install_or_update_engine(
        args.target,
        backend=args.backend,
        version=getattr(args, "version", "latest"),
        bin_dir=Path(args.bin_dir).expanduser() if getattr(args, "bin_dir", None) else None,
        force=bool(args.force),
        dry_run=bool(getattr(args, "dry_run", False)),
        progress=progress,
    )
    if getattr(args, "dry_run", False) or res.action == "dry-run":
        for step in res.steps:
            print(f"  ✓ {step}")
    elif res.ok and res.shim_path:
        print(f"  ✓ Shim ready: {res.shim_path}")
    if not res.ok:
        print(f"[splitch] Engine {args.engine_cmd} failed: {res.error}", file=sys.stderr)
        return 1
    return 0


