def _cmd_desktop(args: argparse.Namespace) -> int:
    if args.desktop_cmd == "install":
        if not args.force and not is_desktop_applicable():
            print("[splitch] Headless session detected — skipped desktop shortcuts (pass --force to override).")
            return 0
        res = install_desktop_integration(
            desktop_icon=not bool(args.no_desktop_icon),
            autostart=bool(args.autostart),
            router_url=args.url,
            mode=args.mode,
            local_service=args.service,
        )
        print(f"[splitch] Desktop integration installed ({res['platform']}):")
        for p in res["installed_paths"]:
            print(f"  ✓ {p}")
        return 0

    if args.desktop_cmd == "uninstall":
        res = uninstall_desktop_integration()
        if res["removed"]:
            for p in res["removed"]:
                print(f"  ✓ Removed {p}")
        else:
            print("[splitch] No desktop shortcuts found to remove.")
        return 0

    if args.desktop_cmd == "sync-icon":
        theme_payload: dict[str, object] | None = None
        if args.accent is not None or args.scheme is not None or args.surface is not None:
            cur = load_desktop_config().theme.model_dump()
            if args.accent is not None:
                cur["accent"] = args.accent.strip()
            if args.scheme is not None:
                cur["scheme"] = args.scheme
                cur["resolved_light"] = args.scheme == "light"
            if args.surface is not None:
                cur["surface"] = args.surface
            theme_payload = cur
        else:
            target_url = (args.url or load_desktop_config().router_url or "http://127.0.0.1:8080").rstrip("/")
            api_key = os.getenv("SPLITCH_API_KEY", "").strip()
            headers = {"Authorization": f"Bearer {api_key}"} if api_key else {}
            try:
                r = httpx.get(f"{target_url}/api/theme", headers=headers, timeout=3.0)
                if r.status_code == 200:
                    theme_payload = r.json()
            except (httpx.HTTPError, ValueError):
                pass
        res = sync_desktop_icons(theme_payload)
        print(f"[splitch] Synced desktop & tray icons ({res['platform']}, tag={res['tag']}):")
        for p in res["updated_paths"]:
            print(f"  ✓ {p}")
        return 0

    if args.desktop_cmd == "check-updates":
        up = check_update(fetch_remote=True)
        eng = get_engine_status(check_remote=True)
        parts: list[str] = []
        if up.update_available:
            parts.append(f"Splitch update available ({up.behind_count} behind)")
        else:
            parts.append(f"Splitch up to date ({up.local_sha or 'local'})")
        if eng.update_available and eng.latest_llama_tag:
            parts.append(f"llama.cpp {eng.latest_llama_tag} available")
        elif eng.latest_llama_tag:
            parts.append(f"llama.cpp {eng.latest_llama_tag} current")
        msg = " • ".join(parts)
        send_desktop_notification("Splitch Updates", msg)
        print(f"[splitch] {msg}")
        return 0

    st = desktop_integration_status()
    if args.json:
        print(json.dumps(st, indent=2))
        return 0
    print(f"Splitch Desktop Status ({st['platform']})")
